-- The benchmark table predates Product Master in shared environments.  Its
-- original key is BENCHMARK_ID, while the Product Master entity uses ID.
-- Add the application key without replacing or dropping the legacy key/data.
DECLARE
    column_count NUMBER;
    next_id NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO column_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'BENCHMARK_RATE'
       AND COLUMN_NAME = 'ID';

    IF column_count = 0 THEN
        -- The legacy table already has an identity key (BENCHMARK_ID). Oracle
        -- permits only one identity column, so the application key is regular
        -- NUMBER data generated by the sequence below.
        EXECUTE IMMEDIATE 'ALTER TABLE BENCHMARK_RATE ADD (ID NUMBER(19))';
        EXECUTE IMMEDIATE 'UPDATE BENCHMARK_RATE SET ID = BENCHMARK_RATE_ID';
    END IF;

    SELECT COUNT(*)
      INTO column_count
      FROM USER_SEQUENCES
     WHERE SEQUENCE_NAME = 'SEQ_BENCHMARK_RATE_ID';

    IF column_count = 0 THEN
        EXECUTE IMMEDIATE
            'SELECT NVL(MAX(ID), 0) + 1 FROM BENCHMARK_RATE'
            INTO next_id;
        EXECUTE IMMEDIATE
            'CREATE SEQUENCE SEQ_BENCHMARK_RATE_ID START WITH ' ||
            next_id || ' INCREMENT BY 1';
    END IF;
END;
