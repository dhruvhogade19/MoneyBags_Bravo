CREATE TABLE BENCHMARK_RATE (
    BENCHMARK_RATE_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BENCHMARK_CODE VARCHAR2(40) NOT NULL,
    ANNUAL_RATE NUMBER(9,4) NOT NULL,
    EFFECTIVE_FROM DATE NOT NULL,
    EFFECTIVE_TO DATE,
    CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
    CREATED_BY VARCHAR2(100) NOT NULL,
    CONSTRAINT UK_BENCHMARK_CODE_FROM UNIQUE (BENCHMARK_CODE, EFFECTIVE_FROM),
    CONSTRAINT CK_BENCHMARK_RATE CHECK (ANNUAL_RATE >= 0),
    CONSTRAINT CK_BENCHMARK_DATES CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO > EFFECTIVE_FROM)
);

CREATE INDEX IDX_BENCHMARK_EFFECTIVE ON BENCHMARK_RATE (BENCHMARK_CODE, EFFECTIVE_FROM, EFFECTIVE_TO);
