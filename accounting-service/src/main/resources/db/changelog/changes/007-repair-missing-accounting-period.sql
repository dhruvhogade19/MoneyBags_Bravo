CREATE TABLE ACCT_ACCOUNTING_PERIOD (
    PERIOD_ID VARCHAR2(36) NOT NULL,
    BUSINESS_DATE DATE NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    OPENED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CLOSED_AT TIMESTAMP(6) WITH TIME ZONE,
    OPENED_BY VARCHAR2(100) NOT NULL,
    CLOSED_BY VARCHAR2(100),
    VERSION_NO NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ACCT_ACCOUNTING_PERIOD PRIMARY KEY (PERIOD_ID),
    CONSTRAINT UQ_ACCT_ACCOUNTING_PERIOD_DATE UNIQUE (BUSINESS_DATE),
    CONSTRAINT CK_ACCT_ACCOUNTING_PERIOD_STATUS
        CHECK (STATUS IN ('OPEN','CLOSING','CLOSED'))
);
