CREATE TABLE ACCT_GL_ACCOUNT (
    GL_ACCOUNT_ID VARCHAR2(36) NOT NULL,
    GL_CODE VARCHAR2(40) NOT NULL,
    NAME VARCHAR2(160) NOT NULL,
    ACCOUNT_TYPE VARCHAR2(20) NOT NULL,
    NORMAL_BALANCE VARCHAR2(10) NOT NULL,
    CURRENCY_CODE CHAR(3) NOT NULL,
    PARENT_GL_CODE VARCHAR2(40),
    STATUS VARCHAR2(20) NOT NULL,
    VERSION_NO NUMBER(19) DEFAULT 0 NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_ACCT_GL_ACCOUNT PRIMARY KEY (GL_ACCOUNT_ID),
    CONSTRAINT UQ_ACCT_GL_ACCOUNT_CODE UNIQUE (GL_CODE),
    CONSTRAINT CK_ACCT_GL_ACCOUNT_TYPE CHECK (ACCOUNT_TYPE IN ('ASSET','LIABILITY','EQUITY','INCOME','EXPENSE')),
    CONSTRAINT CK_ACCT_GL_NORMAL_BALANCE CHECK (NORMAL_BALANCE IN ('DEBIT','CREDIT')),
    CONSTRAINT CK_ACCT_GL_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE ACCT_ACCOUNTING_RULE (
    RULE_ID VARCHAR2(36) NOT NULL,
    RULE_CODE VARCHAR2(60) NOT NULL,
    EVENT_TYPE VARCHAR2(60) NOT NULL,
    COMPONENT_TYPE VARCHAR2(40) NOT NULL,
    PRODUCT_CODE VARCHAR2(40),
    CURRENCY_CODE CHAR(3) NOT NULL,
    RULE_VERSION NUMBER(10) NOT NULL,
    DEBIT_MAPPING_CODE VARCHAR2(60) NOT NULL,
    CREDIT_MAPPING_CODE VARCHAR2(60) NOT NULL,
    EFFECTIVE_FROM DATE NOT NULL,
    EFFECTIVE_TO DATE,
    STATUS VARCHAR2(20) NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_ACCT_ACCOUNTING_RULE PRIMARY KEY (RULE_ID),
    CONSTRAINT UQ_ACCT_RULE_VERSION UNIQUE (RULE_CODE, RULE_VERSION),
    CONSTRAINT CK_ACCT_RULE_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE')),
    CONSTRAINT CK_ACCT_RULE_DATES CHECK (EFFECTIVE_TO IS NULL OR EFFECTIVE_TO >= EFFECTIVE_FROM)
);
CREATE INDEX IX_ACCT_RULE_RESOLUTION ON ACCT_ACCOUNTING_RULE(EVENT_TYPE, COMPONENT_TYPE, CURRENCY_CODE, STATUS);

CREATE TABLE ACCT_SUBLEDGER_MAPPING (
