CREATE TABLE JOURNAL (
    JOURNAL_ID VARCHAR2(36) NOT NULL,
    JOURNAL_NUMBER VARCHAR2(60) NOT NULL,
    POSTING_SEQUENCE NUMBER(19) NOT NULL,
    EXTERNAL_REFERENCE VARCHAR2(160) NOT NULL,
    SOURCE_SERVICE VARCHAR2(80) NOT NULL,
    EVENT_TYPE VARCHAR2(60) NOT NULL,
    OCCURRED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    BUSINESS_DATE DATE NOT NULL,
    CURRENCY_CODE CHAR(3) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    TOTAL_DEBIT NUMBER(19,4) NOT NULL,
    TOTAL_CREDIT NUMBER(19,4) NOT NULL,
    REVERSES_JOURNAL_NUMBER VARCHAR2(60),
    CORRELATION_ID VARCHAR2(64) NOT NULL,
    POSTED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_JOURNAL PRIMARY KEY (JOURNAL_ID),
    CONSTRAINT UQ_JOURNAL_NUMBER UNIQUE (JOURNAL_NUMBER),
    CONSTRAINT UQ_JOURNAL_SEQUENCE UNIQUE (POSTING_SEQUENCE),
    CONSTRAINT UQ_JOURNAL_EXTERNAL_REFERENCE UNIQUE (EXTERNAL_REFERENCE),
    CONSTRAINT FK_JOURNAL_REVERSAL FOREIGN KEY (REVERSES_JOURNAL_NUMBER) REFERENCES JOURNAL(JOURNAL_NUMBER),
    CONSTRAINT CK_JOURNAL_STATUS CHECK (STATUS IN ('POSTED')),
    CONSTRAINT CK_JOURNAL_BALANCED CHECK (TOTAL_DEBIT = TOTAL_CREDIT),
    CONSTRAINT CK_JOURNAL_TOTAL_POSITIVE CHECK (TOTAL_DEBIT > 0)
);
CREATE INDEX IX_JOURNAL_SEARCH ON JOURNAL(BUSINESS_DATE, SOURCE_SERVICE, EVENT_TYPE);

CREATE TABLE JOURNAL_LINE (
    LINE_ID VARCHAR2(36) NOT NULL,
    JOURNAL_ID VARCHAR2(36) NOT NULL,
    LINE_NUMBER NUMBER(10) NOT NULL,
    GL_CODE VARCHAR2(40) NOT NULL,
    SUBLEDGER_REFERENCE VARCHAR2(100),
    COMPONENT_TYPE VARCHAR2(40) NOT NULL,
    RULE_CODE VARCHAR2(60) NOT NULL,
    RULE_VERSION NUMBER(10) NOT NULL,
    DEBIT_AMOUNT NUMBER(19,4) DEFAULT 0 NOT NULL,
    CREDIT_AMOUNT NUMBER(19,4) DEFAULT 0 NOT NULL,
    NARRATION VARCHAR2(500),
    CONSTRAINT PK_JOURNAL_LINE PRIMARY KEY (LINE_ID),
    CONSTRAINT FK_JOURNAL_LINE_HEADER FOREIGN KEY (JOURNAL_ID) REFERENCES JOURNAL(JOURNAL_ID),
    CONSTRAINT FK_JOURNAL_LINE_GL FOREIGN KEY (GL_CODE) REFERENCES GL_ACCOUNT(GL_CODE),
    CONSTRAINT UQ_JOURNAL_LINE UNIQUE (JOURNAL_ID, LINE_NUMBER),
    CONSTRAINT CK_JOURNAL_LINE_SIDE CHECK ((DEBIT_AMOUNT > 0 AND CREDIT_AMOUNT = 0) OR (CREDIT_AMOUNT > 0 AND DEBIT_AMOUNT = 0))
);
CREATE INDEX IX_JOURNAL_LINE_SUBLEDGER ON JOURNAL_LINE(SUBLEDGER_REFERENCE);
CREATE INDEX IX_JOURNAL_LINE_GL ON JOURNAL_LINE(GL_CODE);

