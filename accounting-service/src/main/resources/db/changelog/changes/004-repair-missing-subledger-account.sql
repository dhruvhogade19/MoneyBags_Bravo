CREATE TABLE SUBLEDGER_ACCOUNT (
    SUBLEDGER_ACCOUNT_ID VARCHAR2(36) NOT NULL,
    ACCOUNT_TYPE VARCHAR2(30) NOT NULL,
    ACCOUNT_REFERENCE VARCHAR2(100) NOT NULL,
    PRODUCT_CODE VARCHAR2(40),
    CURRENCY_CODE CHAR(3) NOT NULL,
    LIFECYCLE_STATE VARCHAR2(20) NOT NULL,
    SOURCE_SERVICE VARCHAR2(80) NOT NULL,
    OPENED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CLOSED_AT TIMESTAMP(6) WITH TIME ZONE,
    VERSION_NO NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_SUBLEDGER_ACCOUNT PRIMARY KEY (SUBLEDGER_ACCOUNT_ID),
    CONSTRAINT UQ_SUBLEDGER_ACCOUNT UNIQUE (ACCOUNT_TYPE, ACCOUNT_REFERENCE),
    CONSTRAINT CK_SUBLEDGER_ACCOUNT_TYPE CHECK (ACCOUNT_TYPE IN ('DEPOSIT_ACCOUNT','CREDIT_CARD_ACCOUNT')),
    CONSTRAINT CK_SUBLEDGER_STATE CHECK (LIFECYCLE_STATE IN ('OPEN','CLOSED'))
);

CREATE INDEX IX_SUBLEDGER_REFERENCE
    ON SUBLEDGER_ACCOUNT(ACCOUNT_REFERENCE, LIFECYCLE_STATE);
