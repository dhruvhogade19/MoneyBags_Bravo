CREATE TABLE ACCT_IDEMPOTENCY_RECORD (
    RECORD_ID VARCHAR2(36) NOT NULL,
    SCOPE VARCHAR2(100) NOT NULL,
    KEY_HASH VARCHAR2(64) NOT NULL,
    REQUEST_HASH VARCHAR2(64) NOT NULL,
    RESOURCE_ID VARCHAR2(100),
    HTTP_STATUS NUMBER(3) NOT NULL,
    RESPONSE_BODY CLOB NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_ACCT_IDEMPOTENCY PRIMARY KEY (RECORD_ID),
    CONSTRAINT UQ_ACCT_IDEM_SCOPE_KEY UNIQUE (SCOPE, KEY_HASH)
);

CREATE TABLE ACCT_AUDIT_LOG (
    AUDIT_ID VARCHAR2(36) NOT NULL,
    AGGREGATE_ID VARCHAR2(100) NOT NULL,
    ACTION VARCHAR2(80) NOT NULL,
    OUTCOME VARCHAR2(20) NOT NULL,
    ACTOR_ID VARCHAR2(100),
    ACTOR_TYPE VARCHAR2(30),
    CORRELATION_ID VARCHAR2(64) NOT NULL,
    OCCURRED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_ACCT_AUDIT_LOG PRIMARY KEY (AUDIT_ID)
);
CREATE INDEX IX_ACCT_AUDIT_AGG ON ACCT_AUDIT_LOG(AGGREGATE_ID, OCCURRED_AT);

CREATE TABLE ACCT_TRIAL_BALANCE_RUN (
    RUN_ID VARCHAR2(36) NOT NULL,
    BUSINESS_DATE DATE NOT NULL,
    CURRENCY_CODE CHAR(3) NOT NULL,
    TOTAL_DEBIT NUMBER(19,4) NOT NULL,
    TOTAL_CREDIT NUMBER(19,4) NOT NULL,
    BALANCED_FLAG NUMBER(1) NOT NULL,
    GENERATED_BY VARCHAR2(100) NOT NULL,
    GENERATED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_ACCT_TRIAL_RUN PRIMARY KEY (RUN_ID),
    CONSTRAINT UQ_ACCT_TRIAL_DATE UNIQUE (BUSINESS_DATE, CURRENCY_CODE),
    CONSTRAINT CK_ACCT_TRIAL_FLAG CHECK (BALANCED_FLAG IN (0,1))
);

CREATE TABLE ACCT_TRIAL_BALANCE_LINE (
    LINE_ID VARCHAR2(36) NOT NULL,
    RUN_ID VARCHAR2(36) NOT NULL,
    GL_CODE VARCHAR2(40) NOT NULL,
    DEBIT_TOTAL NUMBER(19,4) NOT NULL,
    CREDIT_TOTAL NUMBER(19,4) NOT NULL,
    CLOSING_BALANCE NUMBER(19,4) NOT NULL,
    CONSTRAINT PK_ACCT_TRIAL_LINE PRIMARY KEY (LINE_ID),
    CONSTRAINT FK_ACCT_TRIAL_RUN FOREIGN KEY (RUN_ID) REFERENCES ACCT_TRIAL_BALANCE_RUN(RUN_ID),
    CONSTRAINT FK_ACCT_TRIAL_GL FOREIGN KEY (GL_CODE) REFERENCES GL_ACCOUNT(GL_CODE),
    CONSTRAINT UQ_ACCT_TRIAL_LINE UNIQUE (RUN_ID, GL_CODE)
);

CREATE TABLE ACCT_FIN_RECON_RUN (
    RUN_ID VARCHAR2(36) NOT NULL,
    EOD_RUN_ID VARCHAR2(80) NOT NULL,
    BUSINESS_DATE DATE NOT NULL,
    CURRENCY_CODE CHAR(3) NOT NULL,
    EXPECTED_COUNT NUMBER(19) NOT NULL,
    ACTUAL_COUNT NUMBER(19) NOT NULL,
    EXPECTED_TOTAL NUMBER(19,4) NOT NULL,
    ACTUAL_TOTAL NUMBER(19,4) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    CREATED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    VERSION_NO NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ACCT_FIN_RECON_RUN PRIMARY KEY (RUN_ID),
    CONSTRAINT UQ_ACCT_FIN_RECON_RUN UNIQUE (EOD_RUN_ID, CURRENCY_CODE),
    CONSTRAINT CK_ACCT_FIN_RECON_STATUS CHECK (STATUS IN ('MATCHED','EXCEPTION','RESOLVED'))
);

CREATE TABLE ACCT_FIN_RECON_ITEM (
    ITEM_ID VARCHAR2(36) NOT NULL,
    RUN_ID VARCHAR2(36) NOT NULL,
    REFERENCE VARCHAR2(160) NOT NULL,
    EXPECTED_AMOUNT NUMBER(19,4) NOT NULL,
    ACTUAL_AMOUNT NUMBER(19,4) NOT NULL,
    DIFFERENCE NUMBER(19,4) NOT NULL,
    BLOCKING_FLAG NUMBER(1) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    RESOLUTION VARCHAR2(1000),
    RESOLVED_BY VARCHAR2(100),
    RESOLVED_AT TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT PK_ACCT_FIN_RECON_ITEM PRIMARY KEY (ITEM_ID),
    CONSTRAINT FK_ACCT_FIN_RECON_RUN FOREIGN KEY (RUN_ID) REFERENCES ACCT_FIN_RECON_RUN(RUN_ID),
    CONSTRAINT CK_ACCT_FIN_RECON_BLOCK CHECK (BLOCKING_FLAG IN (0,1)),
    CONSTRAINT CK_ACCT_FIN_RECON_ITEM CHECK (STATUS IN ('OPEN','RESOLVED','ACCEPTED'))
);
