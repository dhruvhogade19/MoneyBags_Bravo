CREATE TABLE ACCOUNT_LIFECYCLE_EVENT (
    LIFECYCLE_EVENT_ID VARCHAR2(36) NOT NULL,
    EVENT_REFERENCE VARCHAR2(160) NOT NULL,
    IDEMPOTENCY_KEY_HASH VARCHAR2(64) NOT NULL,
    REQUEST_HASH VARCHAR2(64) NOT NULL,
    EVENT_TYPE VARCHAR2(40) NOT NULL,
    ACCOUNT_TYPE VARCHAR2(30) NOT NULL,
    ACCOUNT_REFERENCE VARCHAR2(100) NOT NULL,
    BUSINESS_DATE DATE NOT NULL,
    OCCURRED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    REASON_CODE VARCHAR2(40),
    SOURCE_SERVICE VARCHAR2(80) NOT NULL,
    CORRELATION_ID VARCHAR2(64) NOT NULL,
    PROCESSED_AT TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_ACCOUNT_LIFECYCLE_EVENT PRIMARY KEY (LIFECYCLE_EVENT_ID),
    CONSTRAINT UQ_LIFECYCLE_EVENT_REFERENCE UNIQUE (EVENT_REFERENCE),
    CONSTRAINT UQ_LIFECYCLE_IDEMPOTENCY UNIQUE (IDEMPOTENCY_KEY_HASH),
    CONSTRAINT CK_LIFECYCLE_ACCOUNT_TYPE CHECK (ACCOUNT_TYPE IN ('DEPOSIT_ACCOUNT','CREDIT_CARD_ACCOUNT'))
);

CREATE INDEX IX_LIFECYCLE_ACCOUNT
    ON ACCOUNT_LIFECYCLE_EVENT(ACCOUNT_TYPE, ACCOUNT_REFERENCE, PROCESSED_AT);
