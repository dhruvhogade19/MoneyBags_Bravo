   'SAVINGS', 'INR', 'BR-001', 'SINGLE', 'ACTIVE', SYSTIMESTAMP, 0,
   SYSTIMESTAMP, 'liquibase-seed', SYSTIMESTAMP, 'liquibase-seed', 'POSTMAN-CLOSURE');

