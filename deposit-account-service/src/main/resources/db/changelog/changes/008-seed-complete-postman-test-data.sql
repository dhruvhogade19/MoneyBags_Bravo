-- Extended, idempotent local data for the complete Postman collection.
-- This changeset is installed only under the Liquibase "postman" context.
-- It deliberately creates fixed deposits with historical dates because those
-- states cannot be produced immediately through the booking API.

-- Give the shared payment/funding source enough headroom for repeated local runs.
UPDATE ACCOUNT_BALANCE
   SET LEDGER_BALANCE = 250000,
       AVAILABLE_BALANCE = 250000,
       BLOCKED_AMOUNT = 0,
       PROJECTION_VERSION = PROJECTION_VERSION + 1,
       AS_OF = SYSTIMESTAMP,
       SOURCE_EVENT_ID = 'seed-balance-source-008'
 WHERE ACCOUNT_ID = 'seed-sav-source-001';

-- Zero-balance active CASA account for deterministic closure testing.
