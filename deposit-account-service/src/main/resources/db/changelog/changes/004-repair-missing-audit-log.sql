CREATE TABLE AUDIT_LOG (
    AUDIT_ID VARCHAR2(36) NOT NULL,
    AGGREGATE_ID VARCHAR2(36),
    ACTION VARCHAR2(80) NOT NULL,
    OUTCOME VARCHAR2(20) NOT NULL,
    ACTOR_ID VARCHAR2(100) NOT NULL,
    ACTOR_TYPE VARCHAR2(20) NOT NULL,
    REASON_CODE VARCHAR2(40),
    BEFORE_HASH VARCHAR2(64),
    AFTER_HASH VARCHAR2(64),
    CORRELATION_ID VARCHAR2(64) NOT NULL,
    OCCURRED_AT TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AUDIT_LOG PRIMARY KEY (AUDIT_ID)
);

CREATE INDEX IX_AUDIT_AGGREGATE_TIME ON AUDIT_LOG(AGGREGATE_ID, OCCURRED_AT);
