CREATE TABLE PAYMENT_FD_ACCOUNTING_RECOVERY (
  RECOVERY_ID VARCHAR2(36 CHAR) PRIMARY KEY,
  PAYMENT_ID VARCHAR2(36 CHAR) NOT NULL,
  IDEMPOTENCY_KEY_HASH VARCHAR2(64 CHAR) NOT NULL,
  REQUEST_HASH VARCHAR2(64 CHAR) NOT NULL,
  SOURCE_FINGERPRINT VARCHAR2(64 CHAR) NOT NULL,
  FIXED_DEPOSIT_ID VARCHAR2(100 CHAR) NOT NULL,
  SOURCE_ACCOUNT_ID VARCHAR2(150 CHAR) NOT NULL,
  FD_ACCOUNT_ID VARCHAR2(150 CHAR) NOT NULL,
  AMOUNT NUMBER(19,4) NOT NULL,
  CURRENCY_CODE VARCHAR2(3 CHAR) NOT NULL,
  BUSINESS_DATE DATE NOT NULL,
  ORIGINAL_OCCURRED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
  ACCOUNTING_REFERENCE VARCHAR2(150 CHAR) NOT NULL,
  LEGACY_JOURNAL_NUMBER VARCHAR2(100 CHAR) NOT NULL,
  RECOVERY_JOURNAL_NUMBER VARCHAR2(100 CHAR),
  STATUS VARCHAR2(30 CHAR) NOT NULL,
  OUTCOME VARCHAR2(30 CHAR),
  REASON VARCHAR2(500 CHAR) NOT NULL,
  REQUESTED_BY VARCHAR2(150 CHAR) NOT NULL,
  CORRELATION_ID VARCHAR2(100 CHAR) NOT NULL,
  ATTEMPT_COUNT NUMBER(10) NOT NULL,
  ERROR_CODE VARCHAR2(100 CHAR),
  ERROR_MESSAGE VARCHAR2(500 CHAR),
  CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
  LAST_ATTEMPT_AT TIMESTAMP WITH TIME ZONE NOT NULL,
  COMPLETED_AT TIMESTAMP WITH TIME ZONE,
  CONSTRAINT UK_PAY_FD_REC_PAYMENT UNIQUE (PAYMENT_ID),
  CONSTRAINT UK_PAY_FD_REC_KEY UNIQUE (IDEMPOTENCY_KEY_HASH),
  CONSTRAINT FK_PAY_FD_REC_PAYMENT FOREIGN KEY (PAYMENT_ID) REFERENCES PAYMENT(PAYMENT_ID),
  CONSTRAINT CK_PAY_FD_REC_STATUS CHECK (STATUS IN ('PENDING', 'FAILED', 'COMPLETED')),
  CONSTRAINT CK_PAY_FD_REC_OUTCOME CHECK (OUTCOME IS NULL OR OUTCOME IN ('POSTED', 'ADOPTED')),
  CONSTRAINT CK_PAY_FD_REC_AMOUNT CHECK (AMOUNT > 0),
  CONSTRAINT CK_PAY_FD_REC_ATTEMPT CHECK (ATTEMPT_COUNT > 0)
);
