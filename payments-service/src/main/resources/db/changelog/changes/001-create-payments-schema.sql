CREATE TABLE PAYMENT (
  PAYMENT_ID VARCHAR2(36 CHAR) PRIMARY KEY,
  REQUESTOR_CIF_ID NUMBER(19) NOT NULL,
  IDEMPOTENCY_KEY VARCHAR2(120 CHAR) NOT NULL,
  REQUEST_FINGERPRINT VARCHAR2(64 CHAR) NOT NULL,
  PAYMENT_TYPE VARCHAR2(40 CHAR) NOT NULL,
  SOURCE_INSTRUMENT_TYPE VARCHAR2(30 CHAR) NOT NULL,
  SOURCE_ACCOUNT_ID VARCHAR2(150 CHAR) NOT NULL,
  DESTINATION_INSTRUMENT_TYPE VARCHAR2(30 CHAR) NOT NULL,
  DESTINATION_ACCOUNT_ID VARCHAR2(150 CHAR),
  MERCHANT_ID VARCHAR2(150 CHAR),
  BILL_ID VARCHAR2(100 CHAR),
  FIXED_DEPOSIT_ID VARCHAR2(100 CHAR),
  PRINCIPAL_AMOUNT NUMBER(19,4),
  INTEREST_AMOUNT NUMBER(19,4),
  AMOUNT NUMBER(19,4) NOT NULL,
  CURRENCY_CODE VARCHAR2(3 CHAR) NOT NULL,
  STATUS VARCHAR2(30 CHAR) NOT NULL,
  REFERENCE_TEXT VARCHAR2(255 CHAR),
  DEPOSIT_RESERVATION_ID VARCHAR2(100 CHAR),
  CARD_HOLD_ID VARCHAR2(100 CHAR),
  ACCOUNTING_JOURNAL_NUMBER VARCHAR2(100 CHAR),
  REVERSAL_JOURNAL_NUMBER VARCHAR2(100 CHAR),
  BILLING_SETTLEMENT_AT TIMESTAMP WITH TIME ZONE,
  FAILURE_CODE VARCHAR2(80 CHAR),
  FAILURE_MESSAGE VARCHAR2(500 CHAR),
  CORRELATION_ID VARCHAR2(100 CHAR) NOT NULL,
  BUSINESS_DATE DATE NOT NULL,
  CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
  SETTLED_AT TIMESTAMP WITH TIME ZONE,
  REVERSED_AT TIMESTAMP WITH TIME ZONE,
  VERSION_NO NUMBER(19) DEFAULT 0 NOT NULL,
  CONSTRAINT UK_PAYMENT_CIF_IDEMPOTENCY UNIQUE (REQUESTOR_CIF_ID, IDEMPOTENCY_KEY),
  CONSTRAINT CK_PAYMENT_AMOUNT_POSITIVE CHECK (AMOUNT > 0)
);

CREATE INDEX IDX_PAYMENT_SOURCE_CREATED ON PAYMENT (SOURCE_ACCOUNT_ID, CREATED_AT);
CREATE INDEX IDX_PAYMENT_DEST_CREATED ON PAYMENT (DESTINATION_ACCOUNT_ID, CREATED_AT);
CREATE INDEX IDX_PAYMENT_STATUS_DATE ON PAYMENT (STATUS, BUSINESS_DATE);
CREATE INDEX IDX_PAYMENT_FIXED_DEPOSIT ON PAYMENT (FIXED_DEPOSIT_ID, CREATED_AT);

CREATE TABLE PAYMENT_STATUS_HISTORY (
  HISTORY_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PAYMENT_ID VARCHAR2(36 CHAR) NOT NULL,
  FROM_STATUS VARCHAR2(30 CHAR),
  TO_STATUS VARCHAR2(30 CHAR) NOT NULL,
  REASON_CODE VARCHAR2(80 CHAR),
  REASON_MESSAGE VARCHAR2(500 CHAR),
  CORRELATION_ID VARCHAR2(100 CHAR) NOT NULL,
  CHANGED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT FK_PAYMENT_HISTORY_PAYMENT FOREIGN KEY (PAYMENT_ID) REFERENCES PAYMENT(PAYMENT_ID)
);

CREATE INDEX IDX_PAYMENT_HISTORY_PAYMENT ON PAYMENT_STATUS_HISTORY (PAYMENT_ID, CHANGED_AT);

CREATE TABLE PAYMENT_ATTEMPT (
  ATTEMPT_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  PAYMENT_ID VARCHAR2(36 CHAR) NOT NULL,
  STEP_CODE VARCHAR2(60 CHAR) NOT NULL,
  TARGET_SERVICE VARCHAR2(60 CHAR) NOT NULL,
  OUTCOME VARCHAR2(30 CHAR) NOT NULL,
  HTTP_STATUS NUMBER(3),
  EXTERNAL_REFERENCE VARCHAR2(150 CHAR),
  ERROR_CODE VARCHAR2(100 CHAR),
  STARTED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
  COMPLETED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT FK_PAYMENT_ATTEMPT_PAYMENT FOREIGN KEY (PAYMENT_ID) REFERENCES PAYMENT(PAYMENT_ID)
);

CREATE INDEX IDX_PAYMENT_ATTEMPT_PAYMENT ON PAYMENT_ATTEMPT (PAYMENT_ID, STARTED_AT);
