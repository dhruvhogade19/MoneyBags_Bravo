CREATE TABLE CREDIT_CARD_HOLD
(
    HOLD_ID      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACCOUNT_ID   NUMBER(19) NOT NULL,
    REFERENCE_ID VARCHAR2(128) NOT NULL,
    AMOUNT       NUMBER(19,2) NOT NULL,
    STATUS       VARCHAR2(16) NOT NULL,
    CREATED_AT   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT UQ_CCH_REFERENCE_ID UNIQUE (REFERENCE_ID),
    CONSTRAINT FK_CCH_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES CREDIT_CARD_ACCOUNT (ACCOUNT_ID),
    CONSTRAINT CK_CCH_AMOUNT CHECK (AMOUNT > 0),
    CONSTRAINT CK_CCH_STATUS CHECK (STATUS IN ('HELD', 'CAPTURED', 'RELEASED'))
);
CREATE INDEX IDX_CCH_ACCOUNT ON CREDIT_CARD_HOLD (ACCOUNT_ID);
