CREATE TABLE CREDIT_CARD_APPLICATION
(
    APPLICATION_ID                  NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CIF_ID                          NUMBER(19) NOT NULL,
    PRODUCT_CODE                    VARCHAR2(64) NOT NULL,
    REQUESTED_CREDIT_LIMIT          NUMBER(19,2) NOT NULL,
    APPROVED_CREDIT_LIMIT           NUMBER(19,2),
    PURCHASE_INTEREST_RATE_SNAPSHOT NUMBER(9,4),
    APPLICATION_STATUS              VARCHAR2(16) NOT NULL,
    KYC_STATUS_SNAPSHOT             VARCHAR2(32),
    ELIGIBILITY_STATUS              VARCHAR2(32) NOT NULL,
    SUBMITTED_AT                    TIMESTAMP WITH TIME ZONE NOT NULL,
    UPDATED_AT                      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT CK_CCA_LIMIT CHECK (REQUESTED_CREDIT_LIMIT > 0)
);
CREATE TABLE CREDIT_CARD_ACCOUNT
(
    ACCOUNT_ID                      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    APPLICATION_ID                  NUMBER(19) NOT NULL UNIQUE,
    CIF_ID                          NUMBER(19) NOT NULL,
    PRODUCT_CODE                    VARCHAR2(64) NOT NULL,
    CARD_NUMBER                     VARCHAR2(32) NOT NULL UNIQUE,
    SANCTIONED_LIMIT                NUMBER(19,2) NOT NULL,
    PURCHASE_INTEREST_RATE_SNAPSHOT NUMBER(9,4),
    AVAILABLE_LIMIT                 NUMBER(19,2) NOT NULL,
    OUTSTANDING_AMOUNT              NUMBER(19,2) NOT NULL,
    STATUS                          VARCHAR2(16) NOT NULL,
    OPENED_AT                       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT FK_CCA_APPLICATION FOREIGN KEY (APPLICATION_ID) REFERENCES CREDIT_CARD_APPLICATION (APPLICATION_ID),
    CONSTRAINT CK_CCA_CREDIT_STATE CHECK (AVAILABLE_LIMIT >= 0 AND OUTSTANDING_AMOUNT >= 0 AND
                                          AVAILABLE_LIMIT <= SANCTIONED_LIMIT)
);
CREATE INDEX IDX_CCA_CIF ON CREDIT_CARD_APPLICATION (CIF_ID);
CREATE INDEX IDX_CCC_CIF ON CREDIT_CARD_ACCOUNT (CIF_ID);
