    CHECK (OUTSTANDING_AMOUNT >= 0 AND AVAILABLE_LIMIT <= SANCTIONED_LIMIT);

CREATE TABLE CREDIT_CARD_BILLING_CHARGE
(
    BILLING_CHARGE_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACCOUNT_ID        NUMBER(19) NOT NULL,
    BILL_ID           VARCHAR2(36) NOT NULL UNIQUE,
    JOURNAL_NUMBER    VARCHAR2(64) NOT NULL,
    AMOUNT            NUMBER(19,2) NOT NULL,
    CURRENCY          VARCHAR2(3) NOT NULL,
    APPLIED_AT        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT FK_CCBC_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES CREDIT_CARD_ACCOUNT (ACCOUNT_ID),
    CONSTRAINT CK_CCBC_AMOUNT CHECK (AMOUNT > 0)
);
CREATE INDEX IDX_CCBC_ACCOUNT ON CREDIT_CARD_BILLING_CHARGE (ACCOUNT_ID);
