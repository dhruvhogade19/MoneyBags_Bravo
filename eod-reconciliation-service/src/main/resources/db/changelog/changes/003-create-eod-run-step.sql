CREATE TABLE EOD_RUN_STEP (
    STEP_ID VARCHAR2(100) NOT NULL,
    RUN_ID VARCHAR2(36) NOT NULL,
    STEP_CODE VARCHAR2(60) NOT NULL,
    SEQUENCE_NO NUMBER(3) NOT NULL,
    PROVIDER_SERVICE VARCHAR2(80) NOT NULL,
    HTTP_METHOD VARCHAR2(10) NOT NULL,
    ENDPOINT_PATH VARCHAR2(500) NOT NULL,
    STATUS VARCHAR2(20) NOT NULL,
    COMMAND_REFERENCE VARCHAR2(100) NOT NULL,
    ATTEMPT_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    STARTED_AT TIMESTAMP(6) WITH TIME ZONE,
    COMPLETED_AT TIMESTAMP(6) WITH TIME ZONE,
    ERROR_CODE VARCHAR2(80),
    ERROR_MESSAGE CLOB,
    OUTPUT_JSON CLOB NOT NULL,
    CONSTRAINT PK_EOD_RUN_STEP PRIMARY KEY (STEP_ID),
    CONSTRAINT FK_EOD_RUN_STEP_RUN FOREIGN KEY (RUN_ID) REFERENCES EOD_RUN(RUN_ID),
    CONSTRAINT UQ_EOD_RUN_STEP_CODE UNIQUE (RUN_ID, STEP_CODE),
    CONSTRAINT UQ_EOD_RUN_STEP_SEQUENCE UNIQUE (RUN_ID, SEQUENCE_NO),
    CONSTRAINT CK_EOD_RUN_STEP_STATUS CHECK (STATUS IN ('PENDING','RUNNING','FAILED','COMPLETED'))
);
